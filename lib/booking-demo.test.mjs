import test from 'node:test';
import assert from 'node:assert/strict';
import {createHmac} from 'node:crypto';
import {verifyCalendly,normalizeCalendly} from './booking-demo.ts';
const secret = 'synthetic-test-signing-key-not-a-live-secret';
const raw = JSON.stringify({event:'invitee.created',created_at:'2026-11-02T05:00:00Z',payload:{uri:'https://api.calendly.com/scheduled_events/test/invitees/demo',tracking:{utm_content:'inbound-demo-12345678'}}});
const now = Date.parse('2026-11-02T05:00:00Z');
const timestamp = String(now/1000);
const signature = createHmac('sha256',secret).update(`${timestamp}.${raw}`).digest('hex');
const header = `t=${timestamp},v1=${signature}`;
test('accepts the exact signed payload',()=>assert.equal(verifyCalendly(raw,header,secret,now),true));
test('rejects altered payloads',()=>assert.equal(verifyCalendly(raw+' ',header,secret,now),false));
test('rejects stale timestamps',()=>assert.equal(verifyCalendly(raw,header,secret,now+181000),false));
test('rejects future timestamps',()=>assert.equal(verifyCalendly(raw,header,secret,now-181000),false));
test('rejects malformed signature lengths',()=>assert.equal(verifyCalendly(raw,`t=${timestamp},v1=abc`,secret,now),false));
test('rejects ambiguous timestamps',()=>assert.equal(verifyCalendly(raw,`${header},t=${timestamp}`,secret,now),false));
test('requires the configured key',()=>assert.equal(verifyCalendly(raw,header,'',now),false));
test('maps the tracked demo session and stable event ID',()=>{
  const event=normalizeCalendly(JSON.parse(raw));
  assert.equal(event.session_id,'inbound-demo-12345678');
  assert.equal(event.dry_run,true);
  assert.equal(event.event_id,'invitee.created:https://api.calendly.com/scheduled_events/test/invitees/demo');
});
test('does not map untracked bookings',()=>assert.throws(()=>normalizeCalendly({event:'invitee.created',payload:{}})));
test('does not accept unsupported events',()=>assert.throws(()=>normalizeCalendly({event:'something_else',payload:{}})));
